#[derive(Debug, Clone, Copy)]
pub enum AddressMode {
    Absolute,
    AbsoluteIndirect,
    AbsoluteIndirectLong,
    AbsoluteIndirectX,
    AbsoluteLong,
    AbsoluteLongX,
    AbsoluteX,
    AbsoluteY,
    Accumulator,
    DirectPage,
    DirectPageIndirect,
    DirectPageIndirectLong,
    DirectPageIndirectLongY,
    DirectPageIndirectX,
    DirectPageIndirectY,
    DirectPageX,
    DirectPageY,
    Immediate,
    StackRelative,
    StackRelativeIndirectY,
}
/// Retuns the number of bytes in a 16 bit cpu instruction using the supplied address mode
pub fn get_op_size(address_mode: &AddressMode) -> u8 {
    match address_mode {
        Absolute => 3,
        AbsoluteIndirect => 3,
        AbsoluteIndirectLong => 3,
        AbsoluteIndirectX => 3,
        AbsoluteLong => 4,
        AbsoluteLongX => 4,
        AbsoluteX => 3,
        AbsoluteY => 3,
        Accumulator => 1,
        DirectPage => 2,
        DirectPageIndirect => 2,
        DirectPageIndirectLong => 2,
        DirectPageIndirectLongY => 2,
        DirectPageIndirectX => 2,
        DirectPageIndirectY => 2,
        DirectPageX => 2,
        DirectPageY => 2,
        Immediate => 3,
        StackRelative => 2,
        StackRelativeIndirectY => 2,
    }
}

